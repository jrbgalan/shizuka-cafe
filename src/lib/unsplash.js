const pool = Object.values(CURATED_UNSPLASH_MAP);
const cache = new Map();

function hashString(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) hash = (hash << 5) - hash + str.charCodeAt(i);
  return Math.abs(hash);
}

/**
 * Returns a unique, high-res Unsplash photo URL for any given label, alt, or search phrase.
 */
export function getUnsplashImageUrl(labelOrQuery) {
  if (!labelOrQuery) return pool[0];
  const normalized = labelOrQuery.trim().toLowerCase();

  // 1. Direct match in curated collection
  if (CURATED_UNSPLASH_MAP[normalized]) {
    return CURATED_UNSPLASH_MAP[normalized];
  }

  // 2. Partial / keyword match (supporting both hyphens and spaces)
  for (const [key, url] of Object.entries(CURATED_UNSPLASH_MAP)) {
    const spaceKey = key.replace(/-/g, " ");
    if (
      normalized === key ||
      normalized === spaceKey ||
      normalized.includes(key) ||
      normalized.includes(spaceKey) ||
      key.includes(normalized) ||
      spaceKey.includes(normalized)
    ) {
      return url;
    }
  }

  // 3. Keyword heuristics
  if (normalized.includes("matcha") || normalized.includes("tea")) {
    return CURATED_UNSPLASH_MAP["matcha in a chawan"];
  }
  if (normalized.includes("pour") || normalized.includes("drip") || normalized.includes("v60")) {
    return CURATED_UNSPLASH_MAP["pour-over in a glass carafe"];
  }
  if (normalized.includes("bean") || normalized.includes("roast")) {
    return CURATED_UNSPLASH_MAP["medium roast beans in a ceramic bowl"];
  }
  if (normalized.includes("latte") || normalized.includes("cortado") || normalized.includes("milk")) {
    return CURATED_UNSPLASH_MAP["flat white with latte art"];
  }
  if (normalized.includes("pastry") || normalized.includes("cake") || normalized.includes("muffin") || normalized.includes("toast")) {
    return CURATED_UNSPLASH_MAP["a single pastry on a plate"];
  }
  if (normalized.includes("cafe") || normalized.includes("room") || normalized.includes("interior") || normalized.includes("table")) {
    return CURATED_UNSPLASH_MAP["a calm empty cafe interior in morning light"];
  }

  // 4. Deterministic fallback from pool
  const index = hashString(normalized) % pool.length;
  return pool[index];
}

/**
 * Live API search using the provided Unsplash Access Key with localStorage caching.
 */
export async function searchUnsplashPhoto(query) {
  if (!query) return null;
  const key = query.trim().toLowerCase();

  if (cache.has(key)) return cache.get(key);

  const localCacheKey = `shizuka.unsplash.${key}`;
  try {
    const cached = localStorage.getItem(localCacheKey);
    if (cached) {
      cache.set(key, cached);
      return cached;
    }
  } catch {
    /* ignore */
  }

  try {
    const res = await fetch(
      `https://api.unsplash.com/search/photos?query=${encodeURIComponent(query)}&per_page=1&client_id=${UNSPLASH_ACCESS_KEY}`
    );
    if (!res.ok) throw new Error("Unsplash API response not ok");
    const data = await res.json();
    const photoUrl = data.results?.[0]?.urls?.regular;

    if (photoUrl) {
      cache.set(key, photoUrl);
      try {
        localStorage.setItem(localCacheKey, photoUrl);
      } catch {
        /* ignore */
      }
      return photoUrl;
    }
  } catch (err) {
    console.warn("Unsplash API fetch fallback:", err.message);
  }

  return getUnsplashImageUrl(query);
}
